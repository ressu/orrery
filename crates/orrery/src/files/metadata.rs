//! Gcode metadata, after Moonraker's `file_manager/metadata.py`.
//!
//! The slicer is identified from the file's header, then each `parse_*` field is read with the
//! same regular expressions Moonraker uses. orrery reads PrusaSlicer and its forks (SuperSlicer,
//! OrcaSlicer, and others that keep PrusaSlicer's layout), Slic3r, Slic3r PE, BambuStudio, and
//! Cura. Files from other slicers get the fields any gcode file has.

use std::fs;
use std::io::{Read, Seek, SeekFrom};
use std::path::Path;
use std::time::UNIX_EPOCH;

use anyhow::{Context, Result};
use regex::Regex;
use serde_json::{Map, Value, json};

/// Moonraker reads the first and last MiB of a file.
const READ_SIZE: usize = 1024 * 1024;
const THUMB_FORMATS: &[&str] = &["png", "jpg", "qoi"];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Unknown,
    PrusaSlicer,
    Slic3rPe,
    Slic3r,
    BambuStudio,
    Cura,
}

/// Names that PrusaSlicer's generic pattern also matches, but that have their own parser.
const PRUSA_EXCLUSIONS: &[&str] = &["slic3r prusa edition", "slic3r", "bambustudio"];
const PRUSA_ALIASES: &[&str] =
    &["PrusaSlicer", "SuperSlicer", "OrcaSlicer", "MomentSlicer", "SliCR-3D", "A3dp-Slicer", "QIDISlicer"];

fn re(pattern: &str) -> Regex {
    Regex::new(pattern).expect("metadata patterns are valid")
}

/// Moonraker's placeholders: `(%F)` a float, `(%D)` an integer, `(%S)` the rest of the line.
fn expand(pattern: &str) -> Regex {
    re(&pattern.replace("(%F)", r"([0-9]*\.?[0-9]+)").replace("(%D)", r"([0-9]+)").replace("(%S)", r"(.*)"))
}

fn find_floats(pattern: &str, data: &str) -> Vec<f64> {
    expand(pattern).captures_iter(data).filter_map(|c| c[1].parse().ok()).collect()
}

fn find_ints(pattern: &str, data: &str) -> Vec<i64> {
    expand(pattern).captures_iter(data).filter_map(|c| c[1].parse().ok()).collect()
}

fn find_float(pattern: &str, data: &str) -> Option<f64> {
    expand(pattern).captures(data).and_then(|c| c[1].parse().ok())
}

fn find_int(pattern: &str, data: &str) -> Option<i64> {
    expand(pattern).captures(data).and_then(|c| c[1].parse().ok())
}

fn find_string(pattern: &str, data: &str) -> Option<String> {
    expand(pattern).captures(data).map(|c| c[1].trim_matches('"').to_owned())
}

fn find_min_float(pattern: &str, data: &str) -> Option<f64> {
    find_floats(pattern, data).into_iter().reduce(f64::min)
}

fn find_max_float(pattern: &str, data: &str) -> Option<f64> {
    find_floats(pattern, data).into_iter().reduce(f64::max)
}

/// A list on one line, split at `separators`, with double-quoted items kept whole.
fn find_strings(pattern: &str, separators: &str, data: &str) -> Vec<String> {
    let Some(line) = expand(pattern).captures(data).map(|c| c[1].to_owned()).filter(|l| !l.is_empty()) else {
        return Vec::new();
    };
    let item = re(&format!(r#"\s*(")(?:\\"|[^"])*"\s*|[^{}]+"#, regex::escape(separators)));
    item.captures_iter(&line)
        .filter_map(|m| {
            let mut val = m[0].trim().to_owned();
            if m.get(1).is_some() {
                val = val[1..val.len() - 1].replace("\\\"", "\"").trim().to_owned();
            }
            (!val.is_empty()).then_some(val)
        })
        .collect()
}

/// Python's `json.dumps` of a list of strings, which Moonraker stores for multi-filament files.
fn py_json_list(items: &[String]) -> String {
    let parts: Vec<String> = items.iter().map(|s| Value::from(s.as_str()).to_string()).collect();
    format!("[{}]", parts.join(", "))
}

/// Decodes UTF-8, dropping invalid bytes, as Python's `decode(errors="ignore")` does.
fn decode_lossy(bytes: &[u8]) -> String {
    bytes.utf8_chunks().map(|c| c.valid()).collect()
}

fn first_chars(s: &str, n: usize) -> &str {
    s.char_indices().nth(n).map_or(s, |(i, _)| &s[..i])
}

fn last_chars(s: &str, n: usize) -> &str {
    let count = s.chars().count();
    if count <= n { s } else { &s[s.char_indices().nth(count - n).map_or(0, |(i, _)| i)..] }
}

fn identify(header: &str) -> (Kind, String, String) {
    if let Some(c) = re(r"; BambuStudio[^ ]* ([^\n]+)").captures(header) {
        return (Kind::BambuStudio, "BambuStudio".into(), c[1].to_owned());
    }
    if let Some(c) = re(r"Slic3r\s(\d.*)\son").captures(header) {
        return (Kind::Slic3r, "Slic3r".into(), c[1].to_owned());
    }
    if let Some(c) = re(r"Slic3r\sPrusa\sEdition\s(.*)\son").captures(header) {
        return (Kind::Slic3rPe, "Slic3r PE".into(), c[1].to_owned());
    }
    if let Some(c) = re(r"; generated by (.+?) on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}").captures(header) {
        let (name, version) = c[1].rsplit_once(' ').unwrap_or(("", &c[1]));
        if !PRUSA_EXCLUSIONS.contains(&name.to_lowercase().as_str()) {
            return (Kind::PrusaSlicer, name.to_owned(), version.to_owned());
        }
    } else if let Some(c) = re(&format!(r"({})\s(.*)\son", PRUSA_ALIASES.join("|"))).captures(header) {
        return (Kind::PrusaSlicer, c[1].to_owned(), c[2].to_owned());
    }
    if let Some(c) = re(r"Cura_SteamEngine\s(.*)").captures(header) {
        return (Kind::Cura, "Cura".into(), c[1].to_owned());
    }
    (Kind::Unknown, "Unknown".into(), "?".into())
}

struct Parser<'a> {
    kind: Kind,
    path: &'a Path,
    size: u64,
    data: String,
    header_end: usize,
    footer_start: usize,
    layer_height: Option<f64>,
}

impl Parser<'_> {
    fn header(&self) -> &str {
        &self.data[..self.header_end]
    }

    fn footer(&self) -> &str {
        &self.data[self.footer_start..]
    }

    /// Where PrusaSlicer-style files keep their settings.
    fn config(&self) -> &str {
        if self.kind == Kind::BambuStudio { self.header() } else { self.footer() }
    }

    fn prusa_like(&self) -> bool {
        matches!(self.kind, Kind::PrusaSlicer | Kind::Slic3rPe | Kind::Slic3r | Kind::BambuStudio)
    }

    /// Runs every field parser, in Moonraker's order. Fields with no value are left out.
    fn run(&mut self) -> Map<String, Value> {
        let mut out = Map::new();
        let mut put = |k: &str, v: Option<Value>| {
            if let Some(v) = v {
                out.insert(k.to_owned(), v);
            }
        };
        put("gcode_start_byte", self.gcode_start_byte().map(Value::from));
        put("gcode_end_byte", self.gcode_end_byte().map(Value::from));
        put("layer_count", self.layer_count().map(Value::from));
        put("object_height", self.object_height().map(Value::from));
        put("estimated_time", self.estimated_time());
        put("nozzle_diameter", self.nozzle_diameter().map(Value::from));
        let layer_height = self.layer_height();
        self.layer_height = layer_height;
        put("layer_height", layer_height.map(Value::from));
        put("first_layer_height", self.first_layer_height().map(Value::from));
        put("first_layer_extr_temp", self.first_layer_extr_temp().map(Value::from));
        put("first_layer_bed_temp", self.first_layer_bed_temp().map(Value::from));
        put("chamber_temp", self.chamber_temp().map(Value::from));
        put("filament_name", self.filament_name().map(Value::from));
        put("filament_type", self.filament_type().map(Value::from));
        put("filament_colors", self.prusa_strings(r";\sfilament_colour\s=\s(%S)").map(|v| json!(v)));
        put("filament_change_count", self.filament_change_count().map(Value::from));
        put("extruder_colors", self.prusa_strings(r";\sextruder_colour\s=\s(%S)").map(|v| json!(v)));
        put("filament_temps", self.prusa_int_list(r";\s(?:nozzle_)?temperature\s=\s(%S)"));
        put("referenced_tools", self.prusa_int_list(r";\sreferenced_tools\s=\s(%S)"));
        put("mmu_print", self.prusa(|c| find_int(r";\ssingle_extruder_multi_material\s=\s(%D)", c)).map(Value::from));
        put("filament_total", self.filament_total().map(Value::from));
        put("filament_weight_total", self.filament_weight_total().map(Value::from));
        put("filament_weights", self.filament_weights().map(|v| json!(v)));
        for (field, key) in [
            ("printer_vendor", "printer_vendor"),
            ("printer_model", "printer_model"),
            ("printer_variant", "printer_variant"),
            ("profile_version", "profile_version"),
        ] {
            let v = if self.prusa_like() {
                find_string(&format!("; {key} = (%S)"), self.footer()).map(Value::from)
            } else {
                None
            };
            put(field, v);
        }
        put("thumbnails", self.thumbnails().map(Value::Array));
        out
    }

    /// Runs a PrusaSlicer-family parser on the settings block.
    fn prusa<T>(&self, f: impl Fn(&str) -> Option<T>) -> Option<T> {
        if self.prusa_like() { f(self.config()) } else { None }
    }

    fn prusa_strings(&self, pattern: &str) -> Option<Vec<String>> {
        self.prusa_like().then(|| find_strings(pattern, ",;", self.config()))
    }

    fn prusa_int_list(&self, pattern: &str) -> Option<Value> {
        let items = self.prusa_strings(pattern)?;
        let ints: Option<Vec<i64>> = items.iter().map(|t| t.parse().ok()).collect();
        ints.map(|v| json!(v))
    }

    fn gcode_start_byte(&self) -> Option<usize> {
        re(r"\n[MG]\d+\s.*\n").find(self.header()).map(|m| m.start())
    }

    fn gcode_end_byte(&self) -> Option<u64> {
        let reversed: String = self.footer().chars().rev().collect();
        re(r"\n.*\s\d+[MG]\n").find(&reversed).map(|m| self.size - m.start() as u64)
    }

    fn layer_count(&self) -> Option<i64> {
        match self.kind {
            Kind::BambuStudio => find_int(r"; total layer number: (%D)", self.config()),
            Kind::Cura => find_int(r";LAYER_COUNT\:(%D)", self.header()),
            _ => self.prusa(|c| find_int(r"; total layers count = (%D)", c)),
        }
    }

    fn object_height(&self) -> Option<f64> {
        match self.kind {
            Kind::Unknown => find_max_float(r"G1\sZ(%F)\s", self.footer()),
            Kind::Cura => find_float(r";MAXZ:(%F)", self.header()),
            Kind::BambuStudio => find_float(r"; max_z_height: (%F)", self.config()),
            _ => {
                let layers = re(r";BEFORE_LAYER_CHANGE\n(?:.*\n)?;(\d+\.?\d*)");
                let found: Vec<f64> = layers.captures_iter(self.footer()).filter_map(|c| c[1].parse().ok()).collect();
                found.into_iter().reduce(f64::max).or_else(|| find_max_float(r"G1\sZ(%F)\sF", self.footer()))
            }
        }
    }

    fn estimated_time(&self) -> Option<Value> {
        match self.kind {
            Kind::Cura => find_max_float(r";TIME:(%F)", self.header()).map(Value::from),
            Kind::Slic3r | Kind::Unknown => None,
            _ => {
                let line = re(r";\sestimated\sprinting\stime.*").find(self.config())?.as_str().to_owned();
                let mut total = 0i64;
                for (pattern, mult) in [(r"(\d+)d", 86400), (r"(\d+)h", 3600), (r"(\d+)m", 60), (r"(\d+)s", 1)] {
                    if let Some(c) = re(pattern).captures(&line) {
                        total += c[1].parse::<i64>().ok()? * mult;
                    }
                }
                Some(Value::from(total))
            }
        }
    }

    fn nozzle_diameter(&self) -> Option<f64> {
        match self.kind {
            Kind::Cura => find_float(r";Nozzle\sdiameter\s=\s(%F)", self.header()),
            _ => self.prusa(|c| find_float(r";\snozzle_diameter\s=\s(%F)", c)),
        }
    }

    fn layer_height(&self) -> Option<f64> {
        match self.kind {
            Kind::Cura => find_float(r";Layer\sheight:\s(%F)", self.header()),
            _ => self.prusa(|c| find_float(r"; layer_height = (%F)", c)),
        }
    }

    fn first_layer_height(&self) -> Option<f64> {
        match self.kind {
            Kind::Unknown => find_min_float(r"G1\sZ(%F)\s", self.header()),
            Kind::Cura => find_float(r";MINZ:(%F)", self.header()),
            Kind::BambuStudio => find_float(r"; initial_layer_print_height = (%F)", self.config()),
            _ => {
                if let Some(pct) = find_float(r"; first_layer_height = (%F)%", self.config()) {
                    let lh = self.layer_height?;
                    return Some((pct / 100.0 * lh * 1e6).round() / 1e6);
                }
                find_float(r"; first_layer_height = (%F)", self.config())
            }
        }
    }

    fn first_layer_extr_temp(&self) -> Option<f64> {
        match self.kind {
            Kind::Cura => find_float(r"M109 S(%F)", self.header()),
            Kind::BambuStudio => find_float(r"; nozzle_temperature_initial_layer = (%F)", self.config()),
            _ => self.prusa(|c| find_float(r"; first_layer_temperature = (%F)", c)),
        }
    }

    fn first_layer_bed_temp(&self) -> Option<f64> {
        match self.kind {
            Kind::Cura => find_float(r"M190 S(%F)", self.header()),
            Kind::BambuStudio => find_float(r"; hot_plate_temp_initial_layer = (%F)", self.config()),
            _ => self.prusa(|c| find_float(r"; first_layer_bed_temperature = (%F)", c)),
        }
    }

    fn chamber_temp(&self) -> Option<f64> {
        match self.kind {
            Kind::Cura => find_float(r"M191 S(%F)", self.header()),
            Kind::BambuStudio => find_float(r"; chamber_temperatures = (%F)", self.config()),
            _ => self.prusa(|c| find_float(r"; chamber_temperature = (%F)", c)),
        }
    }

    /// One name, or a JSON list of names for a multi-filament file.
    fn prusa_name_list(&self, pattern: &str) -> Option<String> {
        let found = self.prusa_strings(pattern)?;
        match found.len() {
            0 => None,
            1 => found.into_iter().next(),
            _ => Some(py_json_list(&found)),
        }
    }

    fn filament_name(&self) -> Option<String> {
        match self.kind {
            Kind::Cura => find_string(r";Filament\sname\s=\s(%S)", self.header()),
            _ => self.prusa_name_list(r";\sfilament_settings_id\s=\s(%S)"),
        }
    }

    fn filament_type(&self) -> Option<String> {
        match self.kind {
            Kind::Cura => find_string(r";Filament\stype\s=\s(%S)", self.header()),
            _ => self.prusa_name_list(r";\sfilament_type\s=\s(%S)"),
        }
    }

    fn filament_change_count(&self) -> Option<i64> {
        self.prusa(|c| {
            find_int(r"; total toolchanges = (%D)", c).or_else(|| find_int(r"; total filament change = (%D)", c))
        })
    }

    fn filament_total(&self) -> Option<f64> {
        match self.kind {
            Kind::Unknown => None,
            Kind::Cura => {
                let line = find_string(r";Filament\sused:\s(%S)\n", self.header())?;
                let lengths = find_floats(r"(%F)", &line);
                (!lengths.is_empty()).then(|| lengths.iter().map(|l| l * 1000.0).sum())
            }
            Kind::Slic3rPe => find_float(r"filament\sused\s=\s(%F)mm", self.footer()),
            Kind::Slic3r => find_float(r";\sfilament\_length\_m\s=\s(%F)", self.footer()).map(|m| m * 1000.0),
            Kind::BambuStudio => find_float(r"; total filament length \[mm\] : (%F)", self.config()),
            Kind::PrusaSlicer => {
                let line = find_string(r"filament\sused\s\[mm\]\s=\s(%S)\n", self.config())?;
                let lengths = find_floats(r"(%F)", &line);
                (!lengths.is_empty()).then(|| lengths.iter().sum())
            }
        }
    }

    fn filament_weight_total(&self) -> Option<f64> {
        match self.kind {
            Kind::Unknown => None,
            Kind::Cura => self.filament_weights().map(|w| w.iter().sum()),
            Kind::Slic3r => find_float(r";\sfilament\smass\_g\s=\s(%F)", self.footer()),
            Kind::BambuStudio => find_float(r"; total filament weight \[g\] : (%F)", self.config()),
            _ => find_float(r"total\sfilament\sused\s\[g\]\s=\s(%F)", self.config()),
        }
    }

    fn filament_weights(&self) -> Option<Vec<f64>> {
        let (pattern, data) = match self.kind {
            Kind::Unknown | Kind::BambuStudio => return None,
            Kind::Cura => (r";Filament\sweight\s=\s\[(%S)\]", self.header()),
            _ => (r"filament\sused\s\[g\]\s=\s(%S)\n", self.config()),
        };
        let line = find_string(pattern, data)?;
        let weights = find_floats(r"(%F)", &line);
        (!weights.is_empty()).then_some(weights)
    }

    /// Writes the embedded thumbnails to `.thumbs` next to the file, and makes a 32x32 one if
    /// the slicer didn't.
    fn thumbnails(&self) -> Option<Vec<Value>> {
        if matches!(self.kind, Kind::Slic3r | Kind::Slic3rPe) {
            return None;
        }
        let dir = self.path.parent()?.join(".thumbs");
        if !dir.exists() && fs::create_dir(&dir).is_err() {
            tracing::info!("Unable to create thumb dir: {}", dir.display());
            return None;
        }
        let base = self.path.file_stem()?.to_string_lossy().into_owned();
        let mut found: Vec<(i64, i64, u64, String)> = Vec::new();
        for (tag, body) in thumbnail_blocks(&self.data) {
            let ext = tag.split_once('_').map(|(_, e)| e.to_lowercase()).unwrap_or_else(|| "png".into());
            if !THUMB_FORMATS.contains(&ext.as_str()) {
                tracing::info!("Unsupported thumbnail extension: {ext}");
                continue;
            }
            let cleaned = body.replace("; ", "");
            let lines: Vec<&str> = re(r"\r?\n").split(&cleaned).collect();
            let info = find_ints(r"(%D)", lines[0]);
            let data: String = if lines.len() > 2 { lines[1..lines.len() - 1].concat() } else { String::new() };
            if info.len() != 3 || data.len() as i64 != info[2] {
                tracing::info!("MetadataError: Error parsing thumbnail header: {}", lines[0]);
                continue;
            }
            let dest_ext = if ext == "qoi" { "png" } else { ext.as_str() };
            let name = format!("{base}-{}x{}.{dest_ext}", info[0], info[1]);
            let path = dir.join(&name);
            let Ok(bytes) = base64_decode(&data) else { continue };
            let written = if dest_ext != ext {
                image::load_from_memory(&bytes).ok().and_then(|im| im.save(&path).ok())
            } else {
                fs::write(&path, &bytes).ok()
            };
            if written.is_none() {
                continue;
            }
            let size = fs::metadata(&path).map(|m| m.len()).unwrap_or(0);
            found.push((info[0], info[1], size, format!(".thumbs/{name}")));
        }
        if found.is_empty() {
            return None;
        }
        if !found.iter().any(|t| t.0 == 32 && t.1 == 32) {
            let largest = found.iter().reduce(|a, b| if b.2 > a.2 { b } else { a }).expect("not empty");
            let source = dir.join(largest.3.trim_start_matches(".thumbs/"));
            let small = dir.join(format!("{base}-32x32.png"));
            match make_miniature(&source, &small) {
                Ok((w, h)) => {
                    let size = fs::metadata(&small).map(|m| m.len()).unwrap_or(0);
                    found.insert(0, (w as i64, h as i64, size, format!(".thumbs/{base}-32x32.png")));
                }
                Err(e) => tracing::info!("{e}"),
            }
        }
        Some(
            found
                .into_iter()
                .map(|(w, h, size, rel)| json!({"width": w, "height": h, "size": size, "relative_path": rel}))
                .collect(),
        )
    }
}

/// Finds `; thumbnail[_FMT] begin ... ; thumbnail[_FMT] end` blocks. Returns the tag and the
/// text between `begin` and the closing `; <tag> end`.
fn thumbnail_blocks(data: &str) -> Vec<(String, &str)> {
    // Moonraker's pattern uses a backreference for the closing tag, which Rust's regex doesn't
    // have, so the closing tag is found by hand.
    let open = re(r"(thumbnail(?:_[A-Za-z0-9]+)?) begin");
    let allowed = |c: char| matches!(c, ';' | '/' | '+' | '=') || c.is_alphanumeric() || c == '_' || c.is_whitespace();
    let mut out = Vec::new();
    let mut pos = 0;
    while let Some(c) = open.captures_at(data, pos) {
        let whole = c.get(0).expect("group 0");
        let tag = c[1].to_owned();
        let body_start = whole.end();
        let close = format!("; {tag} end");
        let found = data[body_start..]
            .find(&close)
            .map(|i| body_start + i)
            .filter(|&end| end > body_start && data[body_start..end].chars().all(allowed));
        match found {
            Some(end) => {
                out.push((tag, &data[body_start..end]));
                pos = end + close.len();
            }
            None => pos = whole.start() + 1,
        }
    }
    out
}

fn base64_decode(text: &str) -> Result<Vec<u8>> {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = Vec::with_capacity(text.len() * 3 / 4);
    let mut buf = 0u32;
    let mut bits = 0;
    for b in text.bytes() {
        if b == b'=' {
            break;
        }
        let v = ALPHABET.iter().position(|&a| a == b).context("invalid base64 in thumbnail")? as u32;
        buf = (buf << 6) | v;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buf >> bits) as u8);
        }
    }
    Ok(out)
}

/// Scales an image to fit in 32x32, keeping its shape, as Pillow's `thumbnail` does.
fn make_miniature(source: &Path, dest: &Path) -> Result<(u32, u32)> {
    let im = image::open(source).with_context(|| format!("can't read thumbnail {}", source.display()))?;
    let (w, h) = (im.width(), im.height());
    let (nw, nh) = if w <= 32 && h <= 32 {
        (w, h)
    } else if w >= h {
        (32, ((h as f64 * 32.0 / w as f64).round() as u32).max(1))
    } else {
        (((w as f64 * 32.0 / h as f64).round() as u32).max(1), 32)
    };
    let small = im.resize_exact(nw, nh, image::imageops::FilterType::CatmullRom);
    small.save_with_format(dest, image::ImageFormat::Png)?;
    Ok((nw, nh))
}

/// Reads a gcode file's metadata. Thumbnails are written next to it.
pub fn extract(path: &Path) -> Result<Map<String, Value>> {
    let mut f = fs::File::open(path).with_context(|| format!("opening {}", path.display()))?;
    let meta = f.metadata()?;
    let size = meta.len();
    let mut head = vec![0; READ_SIZE.min(size as usize)];
    f.read_exact(&mut head)?;
    let header = decode_lossy(&head);
    let mut tail = String::new();
    if size as usize > READ_SIZE {
        if size as usize > READ_SIZE * 2 {
            f.seek(SeekFrom::Start(size - READ_SIZE as u64))?;
        }
        let mut rest = Vec::new();
        f.read_to_end(&mut rest)?;
        tail = decode_lossy(&rest);
    }
    let (kind, name, version) = identify(&header);
    let data = header + &tail;
    let header_end = first_chars(&data, READ_SIZE).len();
    let footer_start = data.len() - last_chars(&data, READ_SIZE).len();
    let mut parser = Parser { kind, path, size, data, header_end, footer_start, layer_height: None };
    let modified = meta.modified()?.duration_since(UNIX_EPOCH).map(|d| d.as_secs_f64()).unwrap_or_default();
    let mut out = Map::new();
    out.insert("size".into(), json!(size));
    out.insert("modified".into(), json!(modified));
    out.insert("uuid".into(), json!(uuid::Uuid::new_v4().to_string()));
    out.insert("file_processors".into(), json!([]));
    out.insert("slicer".into(), json!(name));
    out.insert("slicer_version".into(), json!(version));
    out.extend(parser.run());
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture(name: &str) -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../conformance/fixtures/files").join(name)
    }

    fn extract_copy(name: &str) -> Map<String, Value> {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(name);
        fs::copy(fixture(name), &path).unwrap();
        let md = extract(&path).unwrap();
        // Keep the folder until the thumbnails were checked.
        std::mem::forget(dir);
        md
    }

    #[test]
    fn prusaslicer() {
        let md = extract_copy("prusaslicer_cube.gcode");
        assert_eq!(md["slicer"], "PrusaSlicer");
        assert_eq!(md["slicer_version"], "2.7.1+linux-x64-GTK3");
        assert_eq!(md["layer_height"], json!(0.2));
        assert_eq!(md["object_height"], json!(2.0));
        assert_eq!(md["estimated_time"], json!(930));
        assert_eq!(md["filament_total"], json!(1234.56));
        assert_eq!(md["filament_type"], "PLA");
        assert_eq!(md["filament_name"], "Generic PLA");
        let thumbs = md["thumbnails"].as_array().unwrap();
        assert_eq!(thumbs.len(), 2);
        assert_eq!(thumbs[0]["relative_path"], ".thumbs/prusaslicer_cube-32x32.png");
    }

    #[test]
    fn plain() {
        let md = extract_copy("plain.gcode");
        assert_eq!(md["slicer"], "Unknown");
        assert_eq!(md["size"], json!(27));
        assert_eq!(md["object_height"], json!(5.0));
        assert!(md.get("thumbnails").is_none());
        assert!(md.get("gcode_start_byte").is_some());
    }

    #[test]
    fn identifies_slicers() {
        assert_eq!(identify("; generated by SuperSlicer 2.5 on 2026-01-01 at 10:00:00 UTC").1, "SuperSlicer");
        assert_eq!(identify(";Generated with Cura_SteamEngine 5.4.0\n").0, Kind::Cura);
        assert_eq!(identify("; generated by Slic3r 1.3.0 on 2026-01-01 at 10:00:00").0, Kind::Slic3r);
        assert_eq!(identify("G28\n").0, Kind::Unknown);
    }

    #[test]
    fn string_lists() {
        assert_eq!(find_strings(r"; t = (%S)", ",;", "; t = PLA;\"PE,TG\";ABS\n"), vec!["PLA", "PE,TG", "ABS"]);
        assert_eq!(py_json_list(&["a".into(), "b".into()]), r#"["a", "b"]"#);
    }

    #[test]
    fn base64() {
        assert_eq!(base64_decode("aGVsbG8=").unwrap(), b"hello");
    }
}
