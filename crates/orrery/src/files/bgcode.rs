//! PrusaSlicer's binary gcode, `.bgcode`: blocks of metadata, thumbnails, and gcode, each
//! compressed and with a CRC32. [`read`] writes the gcode text PrusaSlicer's own conversion
//! writes (libbgcode's `from_binary_to_ascii`), so the gcode reader finds the metadata as in any
//! PrusaSlicer gcode, and Klipper prints it. The thumbnails, which are images already, are
//! written as files, not as base64 in the gcode (user, 2026-11-27).
//!
//! The format: `libbgcode/doc/specifications.md`, at the commit PrusaSlicer builds with
//! (`PrusaSlicer/deps/+LibBGCode/LibBGCode.cmake`). Each block is read and written on its own,
//! so a large file isn't held in memory.

use std::io::{BufReader, BufWriter, Read, Write};
use std::path::Path;

use anyhow::{Context as _, Result, bail};

use super::readers::Thumbnail;

const MAGIC: &[u8; 4] = b"GCDE";
const VERSION: u32 = 1;
/// No block of PrusaSlicer's is near this; a larger one is a broken file, not a big print.
const MAX_BLOCK: u32 = 64 << 20;

const FILE_METADATA: u16 = 0;
const GCODE: u16 = 1;
const SLICER_METADATA: u16 = 2;
const PRINTER_METADATA: u16 = 3;
const PRINT_METADATA: u16 = 4;
const THUMBNAIL: u16 = 5;

/// Writes the gcode in `input` as text to `gcode` in `dir`, and each thumbnail to a file of its
/// own there, `thumbnail-<n>.png`, `.jpg`, or `.qoi`, which it returns.
pub fn read(input: &Path, dir: &Path, gcode: &str) -> Result<Vec<Thumbnail>> {
    let file = std::fs::File::open(input).with_context(|| format!("can't open {}", input.display()))?;
    let output = dir.join(gcode);
    let out = std::fs::File::create(&output).with_context(|| format!("can't write {}", output.display()))?;
    let mut out = BufWriter::new(out);
    let thumbnails = convert(&mut BufReader::new(file), &mut out, dir)?;
    out.flush().context("can't write the gcode")?;
    Ok(thumbnails)
}

fn convert(src: &mut impl Read, out: &mut impl Write, dir: &Path) -> Result<Vec<Thumbnail>> {
    let mut header = [0u8; 10];
    if src.read_exact(&mut header).is_err() || &header[..4] != MAGIC {
        bail!("it isn't a binary gcode file");
    }
    let version = u32::from_le_bytes(header[4..8].try_into().expect("4 bytes"));
    if version != VERSION {
        bail!("it's binary gcode version {version}, and Orrery reads version {VERSION}");
    }
    let checksum = match u16::from_le_bytes([header[8], header[9]]) {
        0 => false,
        1 => true,
        other => bail!("its checksum type {other} is unknown"),
    };
    // Print and slicer metadata come before the gcode in the file, and after it in the text.
    let mut print_metadata = Vec::new();
    let mut slicer_ini = Vec::new();
    let mut slicer_json = None;
    let mut in_gcode = false;
    let mut thumbnails = Vec::new();
    let mut blocks = 0;
    while let Some(block) = read_block(src, checksum, blocks)? {
        blocks += 1;
        match block.kind {
            FILE_METADATA => {
                let md = ini(&block.data);
                let get = |k: &str| md.iter().find(|(key, _)| key == k).map(|(_, v)| v.as_str());
                let mut producer = get("Producer").unwrap_or("Unknown").to_owned();
                if let Some(on) = get("Produced on") {
                    producer += &format!(" on {on}");
                }
                if let Some(by) = get("Prepared by") {
                    producer += &format!("\n; prepared by {by}");
                }
                write!(out, "; generated by {producer}\n\n\n")?;
            }
            PRINTER_METADATA => write_metadata(out, &ini(&block.data))?,
            THUMBNAIL => {
                let ext = match block.params[0] {
                    0 => "png",
                    1 => "jpg",
                    2 => "qoi",
                    other => {
                        tracing::info!("A binary gcode thumbnail's format {other} is unknown");
                        continue;
                    }
                };
                let file = format!("thumbnail-{}.{ext}", thumbnails.len());
                std::fs::write(dir.join(&file), &block.data).with_context(|| format!("can't write {file}"))?;
                let (width, height) = (u32::from(block.params[1]), u32::from(block.params[2]));
                thumbnails.push(Thumbnail { file, width, height });
            }
            PRINT_METADATA => print_metadata = ini(&block.data),
            SLICER_METADATA if block.params[0] == 1 => {
                slicer_json = Some(String::from_utf8_lossy(&block.data).into_owned())
            }
            SLICER_METADATA => slicer_ini = ini(&block.data),
            GCODE => {
                if !in_gcode {
                    out.write_all(b"\n")?;
                    in_gcode = true;
                }
                let text = match block.params[0] {
                    0 => block.data,
                    1 | 2 => meatpack(&block.data),
                    other => bail!("a gcode block's encoding {other} is unknown"),
                };
                write_without_empty_lines(out, &text)?;
            }
            other => bail!("a block's type {other} is unknown"),
        }
    }
    if !in_gcode {
        bail!("it has no gcode");
    }
    out.write_all(b"\n")?;
    write_metadata(out, &print_metadata)?;
    if let Some(json) = slicer_json {
        write!(out, "\n; prusaslicer_json_config = begin\n; {json}\n; prusaslicer_json_config = end\n")?;
    }
    if !slicer_ini.is_empty() {
        out.write_all(b"\n; prusaslicer_config = begin\n")?;
        write_metadata(out, &slicer_ini)?;
        out.write_all(b"; prusaslicer_config = end\n\n")?;
    }
    Ok(thumbnails)
}

struct Block {
    kind: u16,
    /// The encoding, or a thumbnail's format, width, and height.
    params: [u16; 3],
    /// Uncompressed.
    data: Vec<u8>,
}

/// The next block, or `None` at the end of the file. `n` counts the blocks before it, for the
/// messages.
fn read_block(src: &mut impl Read, checksum: bool, n: usize) -> Result<Option<Block>> {
    let mut head = [0u8; 12];
    match src.read(&mut head[..1])? {
        0 => return Ok(None),
        _ => src.read_exact(&mut head[1..8]).context("it ends in the middle of a block")?,
    }
    let kind = u16::from_le_bytes([head[0], head[1]]);
    let compression = u16::from_le_bytes([head[2], head[3]]);
    let size = u32::from_le_bytes(head[4..8].try_into().expect("4 bytes"));
    let mut head_len = 8;
    let mut stored = size;
    if compression != 0 {
        src.read_exact(&mut head[8..12]).context("it ends in the middle of a block")?;
        stored = u32::from_le_bytes(head[8..12].try_into().expect("4 bytes"));
        head_len = 12;
    }
    if size > MAX_BLOCK || stored > MAX_BLOCK {
        bail!("block {} is too large: {size} bytes", n + 1);
    }
    let mut params_raw = [0u8; 6];
    let params_len = if kind == THUMBNAIL { 6 } else { 2 };
    src.read_exact(&mut params_raw[..params_len]).context("it ends in the middle of a block")?;
    let mut params = [0u16; 3];
    for (i, p) in params.iter_mut().enumerate().take(params_len / 2) {
        *p = u16::from_le_bytes([params_raw[2 * i], params_raw[2 * i + 1]]);
    }
    let mut payload = vec![0u8; stored as usize];
    src.read_exact(&mut payload).context("it ends in the middle of a block")?;
    if checksum {
        let mut sum = [0u8; 4];
        src.read_exact(&mut sum).context("it ends in the middle of a block")?;
        let mut crc = crc32fast::Hasher::new();
        crc.update(&head[..head_len]);
        crc.update(&params_raw[..params_len]);
        crc.update(&payload);
        if crc.finalize() != u32::from_le_bytes(sum) {
            bail!("block {} is damaged: its checksum doesn't match", n + 1);
        }
    }
    let data = match compression {
        0 => payload,
        1 => {
            let mut data = Vec::with_capacity(size as usize);
            flate2::read::ZlibDecoder::new(payload.as_slice())
                .take(u64::from(size) + 1)
                .read_to_end(&mut data)
                .with_context(|| format!("block {} can't be unpacked", n + 1))?;
            data
        }
        2 => heatshrink(&payload, 11, 4, size as usize),
        3 => heatshrink(&payload, 12, 4, size as usize),
        other => bail!("block {}'s compression {other} is unknown", n + 1),
    };
    if data.len() != size as usize {
        bail!("block {} can't be unpacked: it gives {} bytes, not {size}", n + 1, data.len());
    }
    Ok(Some(Block { kind, params, data }))
}

/// `key=value` lines, as libbgcode reads them.
fn ini(data: &[u8]) -> Vec<(String, String)> {
    String::from_utf8_lossy(data)
        .split('\n')
        .filter_map(|line| line.split_once('=').map(|(k, v)| (k.to_owned(), v.to_owned())))
        .collect()
}

fn write_metadata(out: &mut impl Write, md: &[(String, String)]) -> Result<()> {
    for (key, value) in md {
        writeln!(out, "; {key} = {value}")?;
    }
    Ok(())
}

/// Leaves out lines that are empty, or only `;`, as libbgcode does.
fn write_without_empty_lines(out: &mut impl Write, text: &[u8]) -> Result<()> {
    let trim = |s: &[u8]| -> usize { s.iter().filter(|c| !matches!(c, b' ' | b'\t')).count() };
    for line in text.split(|&c| c == b'\n') {
        let rest = match line.iter().position(|c| !matches!(c, b' ' | b'\t')) {
            Some(i) if line[i] == b';' => &line[i + 1..],
            Some(_) => line,
            None => continue,
        };
        if trim(rest) > 0 {
            out.write_all(line)?;
            out.write_all(b"\n")?;
        }
    }
    Ok(())
}

/// Heatshrink, version 0.4: a bit stream, most significant bit first, of `1` and a byte, or `0`
/// and a reference back into what's written so far: `window` bits of distance and `lookahead`
/// bits of length, each one less than its value. What's before the start reads as zeros.
fn heatshrink(src: &[u8], window: u32, lookahead: u32, size: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(size);
    let mut bit = 0usize;
    let mut take = |n: u32| -> Option<usize> {
        let mut v = 0usize;
        for _ in 0..n {
            let byte = *src.get(bit / 8)?;
            v = (v << 1) | usize::from((byte >> (7 - bit % 8)) & 1);
            bit += 1;
        }
        Some(v)
    };
    while out.len() < size {
        match take(1) {
            Some(1) => match take(8) {
                Some(b) => out.push(b as u8),
                None => break,
            },
            Some(_) => {
                let (Some(index), Some(count)) = (take(window), take(lookahead)) else { break };
                let back = index + 1;
                for _ in 0..=count {
                    let b = if back <= out.len() { out[out.len() - back] } else { 0 };
                    out.push(b);
                    if out.len() == size {
                        break;
                    }
                }
            }
            None => break,
        }
    }
    out
}

/// MeatPack, as libbgcode's `MeatPack::unbinarize` reads it: common characters packed two to a
/// byte, and commands after two `0xFF`. Where spaces were left out, it puts them back before a
/// G line's parameters, as PrusaSlicer does.
fn meatpack(src: &[u8]) -> Vec<u8> {
    const SIGNAL: u8 = 0xFF;
    let mut packing = false;
    let mut no_spaces = false;
    let mut cmd_active = false;
    let mut cmd_count = 0;
    let mut char_buf = 0u8;
    let mut full_chars = 0;
    let mut out: Vec<u8> = Vec::with_capacity(src.len() * 2);
    let mut add_space = false;
    let unpacked = |c: u8, no_spaces: bool| match c {
        0..=9 => b'0' + c,
        10 => b'.',
        11 if no_spaces => b'E',
        11 => b' ',
        12 => b'\n',
        13 => b'G',
        14 => b'X',
        _ => 0,
    };
    for &c in src {
        let mut chars: Vec<u8> = Vec::with_capacity(2);
        let mut rx = |c: u8, packing: bool, no_spaces: bool, chars: &mut Vec<u8>| {
            if !packing {
                chars.push(c);
            } else if full_chars > 0 {
                chars.push(c);
                if char_buf > 0 {
                    chars.push(char_buf);
                    char_buf = 0;
                }
                full_chars -= 1;
            } else {
                let first_full = c & 0x0F == 0x0F;
                let second_full = c & 0xF0 == 0xF0;
                let (first, second) = (unpacked(c & 0x0F, no_spaces), unpacked(c >> 4, no_spaces));
                if first_full {
                    full_chars += 1;
                    if second_full {
                        full_chars += 1;
                    } else {
                        char_buf = second;
                    }
                } else {
                    chars.push(first);
                    if first != b'\n' {
                        if second_full {
                            full_chars += 1;
                        } else {
                            chars.push(second);
                        }
                    }
                }
            }
        };
        if c == SIGNAL {
            if cmd_count > 0 {
                cmd_active = true;
                cmd_count = 0;
            } else {
                cmd_count += 1;
            }
        } else if cmd_active {
            match c {
                251 => packing = true,
                250 | 249 => packing = false,
                247 => no_spaces = true,
                246 => no_spaces = false,
                _ => {}
            }
            cmd_active = false;
        } else {
            if cmd_count > 0 {
                rx(SIGNAL, packing, no_spaces, &mut chars);
                cmd_count = 0;
            }
            rx(c, packing, no_spaces, &mut chars);
        }
        for ch in chars {
            let last = out.last().copied();
            let mut new_line = false;
            if ch == b'G' && (last.is_none() || last == Some(b'\n')) {
                add_space = true;
                new_line = true;
            } else if ch == b'\n' {
                add_space = false;
            }
            if !new_line && add_space && last != Some(b' ') && b"XYZEFIJRSGPWHCA".contains(&ch) {
                out.push(b' ');
            }
            if ch != b'\n' || out.last().is_some_and(|&l| l != b'\n') {
                out.push(ch);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn heatshrink_reads_literals_and_references() {
        // "abcabcabc" with window 8, lookahead 4: three literals, then 6 bytes from 3 back.
        let mut bits = String::new();
        for b in b"abc" {
            bits += &format!("1{b:08b}");
        }
        bits += &format!("0{:08b}{:04b}", 2, 5);
        let mut bytes: Vec<u8> = bits
            .as_bytes()
            .chunks(8)
            .map(|c| {
                let s = format!("{:0<8}", String::from_utf8_lossy(c));
                u8::from_str_radix(&s, 2).unwrap()
            })
            .collect();
        bytes.push(0);
        assert_eq!(heatshrink(&bytes, 8, 4, 9), b"abcabcabc");
    }

    #[test]
    fn meatpack_unpacks_and_puts_spaces_back() {
        // Packing on, no spaces on, then "G1X1.5\n": G=13 1=1 -> 0x1D; X=14 1=1 -> 0x1E;
        // .=10 5=5 -> 0x5A; \n=12, with the upper half unused after a newline -> 0x0C.
        let src = [0xFF, 0xFF, 251, 0xFF, 0xFF, 247, 0x1D, 0x1E, 0x5A, 0x0C];
        assert_eq!(String::from_utf8(meatpack(&src)).unwrap(), "G1 X1.5\n");
        // A character that isn't packed: 0b1111 in the lower half, then the byte itself.
        let src = [0xFF, 0xFF, 251, 0x1F, b'M'];
        assert_eq!(String::from_utf8(meatpack(&src)).unwrap(), "M1");
        // Packing off: bytes as they are.
        assert_eq!(meatpack(b"M104 S200\n"), b"M104 S200\n");
    }

    #[test]
    fn blank_lines_and_lone_semicolons_go() {
        let mut out = Vec::new();
        write_without_empty_lines(&mut out, b"G28\n\n;\n  ; \n; kept\nG1 X1\n").unwrap();
        assert_eq!(String::from_utf8(out).unwrap(), "G28\n; kept\nG1 X1\n");
    }

    /// The gcode commands of a file, without comments, blank lines, or extra spaces.
    fn commands(text: &str) -> Vec<String> {
        text.lines()
            .map(|l| l.split(';').next().unwrap_or("").split_whitespace().collect::<Vec<_>>().join(" "))
            .filter(|l| !l.is_empty())
            .collect()
    }

    #[test]
    fn prusaslicers_file_gives_prusaslicers_gcode() {
        // The same slice, which PrusaSlicer 2.9.7 wrote as binary and as text, with two
        // thumbnails added to the binary file (conformance/fixtures/files/README.md).
        let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../conformance/fixtures/files");
        let out = tempfile::tempdir().unwrap();
        let thumbnails = read(&fixtures.join("prusaslicer_cube.bgcode"), out.path(), "model.gcode").unwrap();
        let ours = std::fs::read_to_string(out.path().join("model.gcode")).unwrap();
        let theirs = std::fs::read_to_string(fixtures.join("prusaslicer_cube_bgcode_text.gcode")).unwrap();
        assert_eq!(commands(&ours), commands(&theirs));
        assert!(ours.starts_with("; generated by PrusaSlicer 2.9.7 on "));
        for line in
            ["; estimated printing time (normal mode) = ", "; prusaslicer_config = begin", "; layer_height = 0.3"]
        {
            assert!(ours.contains(line), "{line}");
        }
        // The thumbnails are files, not part of the gcode.
        assert!(!ours.contains("thumbnail begin") && !ours.contains("thumbnail_QOI begin"));
        let files: Vec<(&str, u32, u32)> = thumbnails.iter().map(|t| (t.file.as_str(), t.width, t.height)).collect();
        assert_eq!(files, [("thumbnail-0.png", 16, 16), ("thumbnail-1.qoi", 48, 27)]);
        assert!(std::fs::read(out.path().join("thumbnail-1.qoi")).unwrap().starts_with(b"qoif"));
    }

    #[test]
    fn broken_files_say_why() {
        let dir = tempfile::tempdir().unwrap();
        let err = |b: &[u8]| format!("{:#}", convert(&mut &b[..], &mut Vec::new(), dir.path()).unwrap_err());
        assert!(err(b"G28\n").contains("isn't a binary gcode file"));
        assert!(err(b"GCDE\x02\0\0\0\x01\0").contains("version 2"));
        assert!(err(b"GCDE\x01\0\0\0\x00\0").contains("no gcode"));
        // A gcode block, uncompressed, whose checksum is wrong.
        let mut f = b"GCDE\x01\0\0\0\x01\0".to_vec();
        f.extend_from_slice(&[1, 0, 0, 0, 4, 0, 0, 0, 0, 0]);
        f.extend_from_slice(b"G28\n");
        f.extend_from_slice(&[0, 0, 0, 0]);
        assert!(err(&f).contains("checksum"));
    }
}
